import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import webpush from "web-push";

// Scripts run from the repo root; .env.push is gitignored and mode 600.
const file = path.join(process.cwd(), ".env.push");

function readEnv() {
  if (!existsSync(file)) return new Map();
  const map = new Map();
  for (const raw of readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const index = line.indexOf("=");
    if (index > 0) map.set(line.slice(0, index).trim(), line.slice(index + 1).trim());
  }
  return map;
}

const keys = webpush.generateVAPIDKeys();
const values = readEnv();
values.set("VAPID_PUBLIC_KEY", keys.publicKey);
values.set("VAPID_PRIVATE_KEY", keys.privateKey);
if (!values.get("VAPID_SUBJECT")) {
  values.set("VAPID_SUBJECT", "mailto:admin@zav.baina.mn");
}
values.set("PUSH_DATABASE_URL", values.get("PUSH_DATABASE_URL") ?? "");

const body =
  [
    "# Web Push sender settings — NEVER commit this file.",
    "# Generated by npm run push:keys; keep mode 600 and restrict access.",
    ...Array.from(values.entries()).map(([key, value]) => `${key}=${value}`),
    "",
  ].join("\n");

writeFileSync(file, body, { mode: 0o600 });
console.log("VAPID keys written to .env.push (mode 600).");
console.log("");
console.log("Public key (safe to embed in the app as NEXT_PUBLIC_VAPID_PUBLIC_KEY):");
console.log(keys.publicKey);
console.log("");
console.log("Next: npm run push:role to create the restricted sender role.");
